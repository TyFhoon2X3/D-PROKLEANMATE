create or replace function public.reject_past_booking()
returns trigger
language plpgsql
as $$
begin
  if new.service_date < current_date then
    raise exception 'ไม่สามารถจองย้อนหลังได้';
  end if;
  return new;
end;
$$;

create or replace function public.protect_booking_changes()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    if old.status = 'awaiting_payment'
      and new.status = old.status
      and new.payment_slip_url is not null
      and new.order_number = old.order_number
      and new.user_id = old.user_id
      and new.service_name = old.service_name
      and new.service_price = old.service_price
      and new.service_date is not distinct from old.service_date
      and new.site_visit_date is not distinct from old.site_visit_date
      and new.admin_price is not distinct from old.admin_price
      and new.customer_name = old.customer_name
      and new.customer_phone = old.customer_phone
      and new.customer_email is not distinct from old.customer_email
      and new.service_address = old.service_address
      and new.payment_method = old.payment_method
    then
      return new;
    end if;
    if old.status <> 'pending' then
      raise exception 'รายการนี้ยืนยันแล้ว ไม่สามารถแก้ไขได้';
    end if;
    if new.status <> old.status then
      raise exception 'ผู้ใช้ไม่สามารถเปลี่ยนสถานะรายการจองได้';
    end if;
  end if;
  return new;
end;
$$;

