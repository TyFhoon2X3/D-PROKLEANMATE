create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  service_name text not null,
  service_price text not null,
  service_date date,
  site_visit_date date,
  service_date_confirmed boolean not null default false,
  admin_price numeric(12, 2),
  payment_slip_url text,
  time_slot text,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  service_address text not null,
  payment_method text not null default 'qr' check (payment_method in ('qr', 'cash')),
  status text not null default 'pending' check (status in ('pending', 'quote', 'awaiting_payment', 'confirmed', 'cancelled', 'completed')),
  created_at timestamptz not null default now()
);

