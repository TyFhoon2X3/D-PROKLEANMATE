create or replace function public.reject_same_visit_and_service_date()
returns trigger
language plpgsql
as $$
begin
  if new.site_visit_date is not null
    and new.service_date is not null
    and new.site_visit_date = new.service_date then
    raise exception 'วันที่เข้าประเมินสถานที่ต้องไม่ตรงกับวันที่เข้าทำความสะอาด';
  end if;
  return new;
end;
$$;

create or replace function public.get_unavailable_booking_slots(target_date date)
returns table (time_slot text)
language sql
security definer
set search_path = public
stable
as $$
  select b.time_slot
  from public.bookings b
  where b.service_date = target_date
    and b.status in ('pending', 'confirmed');
$$;

revoke all on function public.get_unavailable_booking_slots(date) from public;
grant execute on function public.get_unavailable_booking_slots(date) to authenticated;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text,
  full_name text,
  phone text,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

insert into public.profiles (id, username, full_name, phone)
select id, raw_user_meta_data ->> 'username', raw_user_meta_data ->> 'full_name', raw_user_meta_data ->> 'phone'
from auth.users
on conflict (id) do nothing;

alter table public.profiles enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

